<?php

namespace Ivandzb\CrudKit\Ports;

/**
 * Database access used by the default data source. Every value goes as a bound
 * parameter ("?" placeholders); implementations must never interpolate them.
 */
interface Connection
{
  const MYSQL = 'mysql';
  const SQLSRV = 'sqlsrv';

  /**
   * @return string Connection::MYSQL or Connection::SQLSRV
   */
  public function driver();

  /**
   * @param string $sql with "?" placeholders
   * @param array $params
   * @return array[] rows as associative arrays
   */
  public function select($sql, array $params = array());

  /**
   * @param string $sql with "?" placeholders
   * @param array $params
   * @return int affected rows
   */
  public function execute($sql, array $params = array());

  /**
   * @return string|null id generated by the last insert on this connection
   */
  public function lastInsertId();
}
